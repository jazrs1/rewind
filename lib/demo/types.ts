// The practice seed: questions, their rewind matches, and the lecture lines around each clip.
// Written by scripts/spike/seed.ts into private/demo/seed.json (real course data, never committed).

import type { QuoteSource } from "../questions/quote-source.ts";
import type { ChoiceLabel, RewindMatch, TranscriptSegment } from "../schema.ts";

export interface SeedQuestion {
  id: string;
  n: number;
  /** The demo course's topic for it (lib/demo/topics.ts); other seeds have none. */
  topic?: string;
  stem: string;
  /** Code shown in the question (see PracticeQuestion.code in lib/pipeline/types.ts). */
  code?: { language: string; lines: string[] } | null;
  choices: { label: ChoiceLabel; text: string }[];
  answer: ChoiceLabel;
  match: Omit<RewindMatch, "questionId" | "recordingUrl" | "slide"> & {
    /** The recording this question's clip is in, when it isn't the set's (generated sets span lectures). */
    recordingUrl?: string;
    /** canvasUrl: the deck's file in Canvas, when the course export is there (opens Canvas's viewer). */
    /**
     * kind "page": a course document's page (syllabus, review sheet), not a lecture slide. A Canvas
     * page has no image (image "", page 0): `excerpt` is its words the question quotes, shown instead.
     * revealsAnswer: a poll or answer slide; nothing shows it (preview, tutor chip, study session)
     * before the student answers (lib/tutor/poll.ts).
     */
    slide: { deck: string; page: number; image: string; canvasUrl?: string; kind?: "slide" | "page"; excerpt?: string; revealsAnswer?: boolean };
  };
  /** Lecturer lines from the example's start to just after the clip, for captions and the transcript. */
  segments: TranscriptSegment[];
  /** Generated questions: one sentence on why the answer is right. Not shown yet. */
  explanation?: string;
  /**
   * Generated questions: the word-for-word quote that supports the answer and where it is
   * (a slide page or a lecture time). Not shown yet. Hand-written questions have none.
   */
  source?: { quote: string; where: QuoteSource };
  /**
   * Quick build (beta, lib/quick/): a question written from the student's own course text. `label` names the source
   * where the sheet names a slide ("Lecture, Oct 22 · 57:43" or "Page: Hash tables"), `where` completes "It's on …",
   * and `quote` is the word-for-word text shown under the graded question. Absent everywhere else.
   */
  quick?: { label: string; where: string; quote: string };
}

/** One moment the lecturer flagged (exam radar), with the phrases that matched it. */
export interface RadarMoment {
  start: number;
  kinds: string[];
  phrases: string[];
  /** The line he said, word for word. */
  text: string;
  /** Lecturer lines around it (20 s each side), for the player. */
  context: TranscriptSegment[];
}

export interface PracticeSeed {
  course: { code: string; name: string };
  set: string;
  lecturer: { name: string; short: string };
  recordingUrl: string;
  questions: SeedQuestion[];
  /** Which questions these are: John's hand-written set, or generated by Claude from each clip. */
  questionSet?: "hand" | "generated";
  /** Exam radar moments from the same lecture, in time order. */
  radar?: RadarMoment[];
  lectureTitle?: string;
}

/** "Stem text (A) one (B) two (C) three (D) four" → stem and choices. */
export function parseQuestionLine(line: string): { stem: string; choices: { label: ChoiceLabel; text: string }[] } {
  const parts = line.split(/\s*\(([A-D])\)\s*/);
  const stem = parts[0].trim();
  const choices: { label: ChoiceLabel; text: string }[] = [];
  for (let i = 1; i + 1 < parts.length; i += 2) choices.push({ label: parts[i] as ChoiceLabel, text: parts[i + 1].trim() });
  return { stem, choices };
}
